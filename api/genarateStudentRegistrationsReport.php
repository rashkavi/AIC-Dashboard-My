<?php
ob_start();

require_once("../includes/UserClass.php");
require_once("../includes/connection.php");
require_once("../includes/UserPermissionsClass.php");
require_once("../includes/Project.php");
require_once("../vendor/autoload.php");

use PhpOffice\PhpSpreadsheet\IOFactory;
use PhpOffice\PhpSpreadsheet\Writer\Xlsx;
use PhpOffice\PhpSpreadsheet\Style\Border;
use PhpOffice\PhpSpreadsheet\Style\Alignment;

/*
    Students Registrations Report
    ------------------------------
    Mirrors the same query/joins used on the Registrations list page
    (inquiries list) so the export never disagrees with what's shown
    on screen, but without pagination — every matching row is written.

    Template layout (students-registrations-report.xlsx):
      Row 1   : Title (B1:E1)
      Row 3-4 : Generated By / Generated On (C3:D3 / C4:D4)
      Row 6-12: Filter summary labels (B:C) / values (D)
                Branch, Faculty, Programme, Intake, Counselor,
                Registration Status, Payment Status
      Row 14  : Column headers
      Row 15+ : Data

    NOTE: the list page's "sort-selector" filters lead_student_status
    (workflow status, e.g. Registered/Verified/etc). The template's
    last column is "Status (Active/Inactive)", which is a DIFFERENT
    field - students_has_intakes.status_status_id - same pattern used
    on the outstanding-balances report. Confirm this mapping is what
    you want; it's a one-line change in the SELECT/column-write below
    if you'd rather show the lead_student_status name in column L.
*/

/* Small helper: resolve a filter id to its display name for the
   report's filter-summary header rows, falling back to "All". */

function resolveFilterLabel(string $table, string $idColumn, string $nameColumn, string $id): string
{
    if (empty($id) || $id === '0') {
        return "All";
    }
    $res = Database::search("SELECT `$nameColumn` AS name FROM `$table` WHERE `$idColumn` = '" . (int)$id . "' LIMIT 1");
    if ($res && $res->num_rows > 0) {
        return $res->fetch_assoc()['name'];
    }
    return "All";
}

try {
    if (!SessionUser::hasValidSession()) {
        throw new Exception("Authentication Failed!");
    }

    if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
        http_response_code(400);
        throw new Exception("Invalid request method");
    }

    if (!isset($_SERVER['CONTENT_TYPE']) || $_SERVER['CONTENT_TYPE'] != 'application/json') {
        http_response_code(400);
        throw new Exception("Invalid JSON");
    }

    $sessionUserObject = SessionUser::getCurrentUserObject();
    $sessionUserRole   = SessionUser::getCurrentUserRole();

    $content = trim(file_get_contents('php://input'));
    $decoded = json_decode($content, true);

    if (json_last_error() != JSON_ERROR_NONE) {
        http_response_code(400);
        throw new Exception("Invalid JSON");
    }

    $text          = isset($decoded['text']) ? Database::escape($decoded['text']) : "";
    $sort          = isset($decoded['sort']) ? Database::escape($decoded['sort']) : "";           // lead_student_status_id (Registration Status)
    $branch        = isset($decoded['branch']) ? Database::escape($decoded['branch']) : "";
    $faculty       = isset($decoded['faculty']) ? Database::escape($decoded['faculty']) : "";
    $programme     = isset($decoded['programme']) ? Database::escape($decoded['programme']) : "";
    $intake        = isset($decoded['intake']) ? Database::escape($decoded['intake']) : "";
    $user          = isset($decoded['user']) ? Database::escape($decoded['user']) : "";            // counselor filter
    $paymentStatus = isset($decoded['paymentStatus']) ? Database::escape($decoded['paymentStatus']) : ""; // 1 = Has Due, 2 = No Due

    date_default_timezone_set('Asia/Colombo');

    $spreadsheet = IOFactory::load("../assets/uploads/reports/registrations-report.xlsx");
    $sheet = $spreadsheet->getActiveSheet();

    /* ---------------- Filter summary header rows ---------------- */

    $sheet->setCellValue("D6", resolveFilterLabel("branches", "branch_id", "branch", $branch));
    $sheet->setCellValue("D7", resolveFilterLabel("faculties", "faculty_id", "faculty", $faculty));
    $sheet->setCellValue("D8", resolveFilterLabel("programmes", "programme_id", "programme", $programme));
    $sheet->setCellValue("D9", resolveFilterLabel("intakes", "intake_id", "intake", $intake));

    if (!empty($user) && $user != '0') {
        $counselorRow = Database::search("
            SELECT CONCAT(`title`.`title`, '.', `users`.`user_fname`, ' ', `users`.`user_lname`) AS name
            FROM `users`
            INNER JOIN `title` ON `users`.`title_title_id` = `title`.`title_id`
            WHERE `users`.`user_id` = '" . (int)$user . "'
            LIMIT 1
        ");
        $sheet->setCellValue("D10", ($counselorRow && $counselorRow->num_rows > 0) ? $counselorRow->fetch_assoc()['name'] : "All");
    } else {
        $sheet->setCellValue("D10", "All");
    }

    if (!empty($sort) && $sort != '0') {
        $statusRow = Database::search("SELECT `lead_student_status` FROM `lead_student_status` WHERE `lead_student_status_id` = '" . (int)$sort . "' LIMIT 1");
        $sheet->setCellValue("D11", ($statusRow && $statusRow->num_rows > 0) ? $statusRow->fetch_assoc()['lead_student_status'] : "All");
    } else {
        $sheet->setCellValue("D11", "All");
    }

    if (!empty($paymentStatus) && $paymentStatus != '0') {
        $sheet->setCellValue("D12", $paymentStatus == '1' ? "Has Due Payments" : "No Due Payments");
    } else {
        $sheet->setCellValue("D12", "All");
    }

    /* ---------------- Main query (same joins as the list page) ---------------- */

    $query = "
        SELECT
            `students`.`student_id` AS `sId`,
            `login_details`.`first_name`,
            `login_details`.`last_name`,
            `login_details`.`email`,
            `students`.`mobile`,
            `login_details`.`whatsapp`,
            `login_details`.`date_registered`,
            `title`.`title`,

            `lead_student_status`.`lead_student_status`,
                                                                                `lead_student_status`.`lead_student_status_id`,

            `branches`.`branch`,
            `faculties`.`faculty`,
            `programmes`.`programme`,
            `intakes`.`intake`,

            `users`.`user_fname`,
            `users`.`user_lname`,
            `title2`.`title` AS `user_title`,

            `status`.`status`,

            `students_has_intakes`.`students_has_intakes_id`,

            CASE
                WHEN `payment`.`students_has_intakes_students_has_intakes_id` IS NOT NULL
                    THEN 1
                ELSE 0
            END AS `has_due_payment`

        FROM `students`

        INNER JOIN `login_details`
            ON `students`.`login_details_login_details_id` = `login_details`.`login_details_id`

        INNER JOIN `title`
            ON `students`.`title_title_id` = `title`.`title_id`

        INNER JOIN `lead_student_status`
            ON `students`.`lead_student_status_lead_student_status_id` = `lead_student_status`.`lead_student_status_id`

        INNER JOIN `students_has_intakes`
            ON `students`.`student_id` = `students_has_intakes`.`students_student_id`

        INNER JOIN `intakes`
            ON `intakes`.`intake_id` = `students_has_intakes`.`intakes_intake_id`

        INNER JOIN `programmes`
            ON `programmes`.`programme_id` = `intakes`.`programmes_programme_id`

        INNER JOIN `faculties`
            ON `faculties`.`faculty_id` = `programmes`.`faculties_faculty_id`

        INNER JOIN `branches`
            ON `branches`.`branch_id` = `faculties`.`branches_branch_id`

        INNER JOIN `users`
            ON `students`.`users_user_id` = `users`.`user_id`

        INNER JOIN `title` AS `title2`
            ON `users`.`title_title_id` = `title2`.`title_id`

        LEFT JOIN `status`
            ON `students_has_intakes`.`status_status_id` = `status`.`status_id`

        LEFT JOIN (
            SELECT DISTINCT `pshi`.`students_has_intakes_students_has_intakes_id`
            FROM `course_payments` AS `cp`
            INNER JOIN `payment_plan_has_students_has_intakes` AS `pshi`
                ON `cp`.`payment_plan_has_students_has_intakes_id` = `pshi`.`payment_plan_has_students_has_intakes_id`
            WHERE `cp`.`payment_status_payment_status_id` = '1'
            AND `cp`.`due_date` < '" . date("Y-m-d") . "'
        ) AS `payment`
            ON `payment`.`students_has_intakes_students_has_intakes_id` = `students_has_intakes`.`students_has_intakes_id`

        WHERE 1=1
    ";

    if ($sessionUserRole == "Counselor") {
        $query .= " AND `users`.`user_id` = '" . $sessionUserObject['user_id'] . "' ";
    } elseif ($sessionUserRole == "Branch Manager") {
        $managerRow = Database::search("SELECT * FROM `users` WHERE `user_id` = '" . $sessionUserObject['user_id'] . "'")->fetch_assoc();
        $query .= " AND (
            `users`.`user_id` = '" . $sessionUserObject['user_id'] . "'
            OR `faculties`.`branches_branch_id` = '" . $managerRow['branches_branch_id'] . "'
        ) ";
    }

    if (!empty($text)) {
        $query .= " AND (
            `students`.`student_id` LIKE '%$text%'
            OR `login_details`.`first_name` LIKE '%$text%'
            OR `login_details`.`last_name` LIKE '%$text%'
            OR `login_details`.`email` LIKE '%$text%'
            OR `students`.`mobile` LIKE '%$text%'
        ) ";
    }
    if (!empty($branch) && $branch != '0') {
        $query .= " AND `faculties`.`branches_branch_id` = '$branch' ";
    }
    if (!empty($faculty) && $faculty != '0') {
        $query .= " AND `faculties`.`faculty_id` = '$faculty' ";
    }
    if (!empty($programme) && $programme != '0') {
        $query .= " AND `programmes`.`programme_id` = '$programme' ";
    }
    if (!empty($intake) && $intake != '0') {
        $query .= " AND `intakes`.`intake_id` = '$intake' ";
    }
    if (!empty($user) && $user != '0') {
        $query .= " AND `users`.`user_id` = '$user' ";
    }
    if (!empty($sort) && $sort != '0') {
        $query .= " AND `lead_student_status`.`lead_student_status_id` = '$sort' ";
    }
    if (!empty($paymentStatus) && $paymentStatus != '0') {
        if ($paymentStatus == '1') {
            $query .= " AND `payment`.`students_has_intakes_students_has_intakes_id` IS NOT NULL ";
        } elseif ($paymentStatus == '2') {
            $query .= " AND `payment`.`students_has_intakes_students_has_intakes_id` IS NULL ";
        }
    }

    $query .= " ORDER BY `login_details`.`date_registered` DESC, `students`.`student_id` DESC ";

    $results = Database::search($query);

    /* ---------------- Write data rows ---------------- */

    $headerRow = 14;
    $row = $headerRow + 1;

    $totalStudents  = 0;
    $activeCount    = 0;
    $inactiveCount  = 0;

    while ($data = $results->fetch_assoc()) {

        $studentName = trim($data['title'] . '. ' . $data['first_name'] . ' ' . $data['last_name']);
        $assignedUser = trim($data['user_title'] . '. ' . $data['user_fname'] . ' ' . $data['user_lname']);
        $statusLabel = $data['status'] ?? '';

        $totalStudents++;
        if (strtolower($statusLabel) === 'active') {
            $activeCount++;
        } else {
            $inactiveCount++;
        }

        $sheet->setCellValue("B$row", $studentName);
        $sheet->setCellValue("C$row", $data['email']);
        $sheet->setCellValue("D$row", $data['mobile']);
        $sheet->setCellValue("E$row", $data['whatsapp']);
        $sheet->setCellValue("F$row", $data['branch']);
        $sheet->setCellValue("G$row", $data['faculty']);
        $sheet->setCellValue("H$row", $data['programme']);
        $sheet->setCellValue("I$row", $data['intake']);
        $sheet->setCellValue("J$row", $assignedUser);
        $sheet->setCellValue("K$row", date("Y-m-d h:i A", strtotime($data['date_registered'])));
        $sheet->setCellValue("L$row", $data['lead_student_status']);

        $sheet->getStyle("B$row:L$row")
            ->getBorders()
            ->getAllBorders()
            ->setBorderStyle(Border::BORDER_THIN);

        $row++;
    }

    $lastDataRow = $row - 1;

    $userData = Database::search("SELECT * FROM `users`
        INNER JOIN `title` ON `users`.`title_title_id` = `title`.`title_id`
        WHERE `user_id`='" . $sessionUserObject['user_id'] . "'")->fetch_assoc();

    $sheet->setCellValue("C3", $userData['title'] . " " . $userData['user_fname'] . " " . $userData['user_lname']);
    $sheet->setCellValue("C4", date("Y-m-d h:i A"));

    $fileName = "students_registrations_report_" . date('Ymd_His') . ".xlsx";

    ob_end_clean();

    header('Content-Type: application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
    header('Content-Disposition: attachment; filename="' . $fileName . '"');
    header('Cache-Control: max-age=0');

    $writer = new Xlsx($spreadsheet);
    $writer->save('php://output');
    exit;
} catch (Exception $e) {
    if (ob_get_length()) {
        ob_end_clean();
    }

    header('Content-Type: application/json');
    echo json_encode([
        "error" => $e->getMessage()
    ]);
    exit;
}
